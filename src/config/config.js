import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isIP } from 'node:net';

export const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../..');

function boolean(env, name, fallback) {
  const value = env[name];
  if (value === undefined || value === '') return fallback;
  if (value !== 'true' && value !== 'false') throw new Error(`${name} must be true or false.`);
  return value === 'true';
}

function integer(env, name, fallback, min, max) {
  const value = env[name] ?? String(fallback);
  if (!/^\d+$/.test(value) || !Number.isSafeInteger(Number(value)) || Number(value) < min || Number(value) > max) throw new Error(`${name} must be an integer between ${min} and ${max}.`);
  return Number(value);
}

function json(env, name, fallback) {
  try { return env[name] ? JSON.parse(env[name]) : fallback; }
  catch { throw new Error(`${name} must contain valid JSON.`); }
}

export function validateUsers(users) {
  if (!Array.isArray(users)) throw new Error('REGISTRY_USERS must be an array.');
  const seen = new Set();
  for (const user of users) {
    if (!user || typeof user.username !== 'string' || !/^[a-zA-Z0-9_.-]{1,64}$/.test(user.username) || seen.has(user.username)) throw new Error('Registry usernames must be unique and use letters, digits, dot, dash or underscore.');
    seen.add(user.username);
    if (!/^scrypt\$[a-f0-9]{32}\$[a-f0-9]{128}$/.test(user.passwordHash)) throw new Error('Registry users need a passwordHash generated by the password CLI.');
    if (!Array.isArray(user.permissions) || !user.permissions.every(rule => rule && typeof rule.repository === 'string' && /^local\/[a-z0-9_./*-]+$/.test(rule.repository) && !rule.repository.includes('..') && (!rule.repository.includes('*') || rule.repository.endsWith('/*') && rule.repository.indexOf('*') === rule.repository.length - 1) && Array.isArray(rule.actions) && rule.actions.every(action => ['pull', 'push'].includes(action)))) throw new Error('User permissions require local repository paths and pull/push actions.');
    if (user.admin !== undefined && typeof user.admin !== 'boolean') throw new Error('User admin must be a boolean.');
  }
  return users;
}

export function loadConfig(env = process.env) {
  const host = env.HOST || '127.0.0.1';
  if (!isIP(host) && host !== 'localhost') throw new Error('HOST must be an IP address or localhost.');
  const port = integer(env, 'PORT', 5000, 0, 65535);
  let publicUrl;
  try {
    publicUrl = new URL(env.PUBLIC_URL || `http://${isIP(host) === 6 ? `[${host}]` : host}:${port}`);
    if (!['http:', 'https:'].includes(publicUrl.protocol) || publicUrl.username || publicUrl.password || publicUrl.pathname !== '/' || publicUrl.search || publicUrl.hash) throw new Error();
  } catch { throw new Error('PUBLIC_URL must be an HTTP(S) origin without credentials or a path.'); }
  const pushEnabled = boolean(env, 'PUSH_ENABLED', false);
  if (pushEnabled && publicUrl.protocol !== 'https:' && !['127.0.0.1', '[::1]', 'localhost'].includes(publicUrl.hostname)) throw new Error('Push requires an HTTPS PUBLIC_URL, except on loopback.');
  if (pushEnabled && !['127.0.0.1', '::1', 'localhost'].includes(host)) throw new Error('Authenticated Push requires a loopback HOST. Use a local HTTPS reverse proxy for remote access.');
  const accounts = json(env, 'DOCKER_HUB_ACCOUNTS', []);
  if (!Array.isArray(accounts) || accounts.some(account => !account || !/^[a-zA-Z0-9_.-]{1,128}$/.test(account.username) || typeof account.token !== 'string' || !account.token || account.token.length > 4096 || /[\r\n]/.test(account.token)) || new Set(accounts.map(account => account.username)).size !== accounts.length) throw new Error('DOCKER_HUB_ACCOUNTS must contain unique username/token profiles.');
  const logLevel = env.LOG_LEVEL || 'info';
  if (!['debug', 'info', 'warn', 'error', 'silent'].includes(logLevel)) throw new Error('LOG_LEVEL must be debug, info, warn, error or silent.');
  const dataDir = resolve(projectRoot, env.DATA_DIR || 'data');
  if (dataDir !== resolve(projectRoot, 'data') && !dataDir.startsWith(`${resolve(projectRoot, 'data')}/`)) throw new Error('DATA_DIR must be data or a directory beneath data/. Mount external storage there.');
  return {
    host, port, publicUrl: publicUrl.origin, pushEnabled, dataDir, logLevel,
    users: validateUsers(json(env, 'REGISTRY_USERS', [])), accounts: accounts.map(({ username, token }) => ({ username, token })),
    accountFailover: boolean(env, 'DOCKER_HUB_ACCOUNT_FAILOVER', false),
    syncEnabled: boolean(env, 'SYNC_ENABLED', true),
    syncIntervalMs: integer(env, 'SYNC_INTERVAL_MINUTES', 360, 1, 525600) * 60000,
    connectivityEnabled: boolean(env, 'CONNECTIVITY_CHECK_ENABLED', true),
    archiveConcurrency: integer(env, 'ARCHIVE_CONCURRENCY', 2, 1, 16),
    downloadConcurrency: integer(env, 'DOWNLOAD_CONCURRENCY', 6, 1, 64),
    foregroundDownloads: integer(env, 'FOREGROUND_DOWNLOAD_CONCURRENCY', 2, 1, 64),
    requestTimeoutMs: integer(env, 'UPSTREAM_TIMEOUT_SECONDS', 120, 1, 3600) * 1000,
    connectTimeoutMs: integer(env, 'UPSTREAM_CONNECT_TIMEOUT_SECONDS', 5, 1, 60) * 1000,
    headerTimeoutMs: integer(env, 'UPSTREAM_HEADER_TIMEOUT_SECONDS', 10, 1, 120) * 1000,
    headerBudgetMs: integer(env, 'UPSTREAM_HEADER_BUDGET_SECONDS', 25, 1, 120) * 1000,
    idleTimeoutMs: integer(env, 'UPSTREAM_IDLE_TIMEOUT_SECONDS', Number(env.UPSTREAM_TIMEOUT_SECONDS || 120), 1, 3600) * 1000,
    upstreamRetries: integer(env, 'UPSTREAM_RETRIES', 2, 0, 5),
    retryBackoffMs: integer(env, 'UPSTREAM_RETRY_BACKOFF_MS', 250, 1, 5000),
    maxBlobBytes: integer(env, 'MAX_BLOB_BYTES', 100 * 1024 ** 3, 1, Number.MAX_SAFE_INTEGER),
    maxManifestBytes: integer(env, 'MAX_MANIFEST_BYTES', 8 * 1024 ** 2, 1024, 64 * 1024 ** 2),
    maxDepth: 16, maxDescriptors: 10000,
    providers: {
      dockerhub: { enabled: boolean(env, 'DOCKER_HUB_ENABLED', true), origin: 'https://registry-1.docker.io', authOrigins: ['https://auth.docker.io'], cdnHosts: ['production.cloudflare.docker.com', 'production.cloudfront.docker.com', 'docker-images-prod.6aa30f8b08e16409b46e0173d6de2f56.r2.cloudflarestorage.com'] },
      ghcr: { enabled: boolean(env, 'GHCR_ENABLED', true), origin: 'https://ghcr.io', authOrigins: ['https://ghcr.io'], cdnHosts: ['pkg-containers.githubusercontent.com'] },
      quay: { enabled: boolean(env, 'QUAY_ENABLED', true), origin: 'https://quay.io', authOrigins: ['https://quay.io'], cdnHosts: ['cdn.quay.io', '.quay.io', 'quayio-production-s3.s3.amazonaws.com'] }
    }
  };
}

export function loadEnvironment() {
  try { process.loadEnvFile(resolve(projectRoot, '.env')); }
  catch (error) { if (error.code !== 'ENOENT') throw new Error('Unable to read the optional .env file.'); }
}
